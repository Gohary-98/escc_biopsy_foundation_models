KIND_DESCRIPTIONS = {
    "id": "identifier string",
    "date": "date, parsed from free text",
    "float": "decimal",
    "int": "integer",
    "code": "categorical code — see `code_legends.yaml`",
    "stage": "stage, split into `_num` / `_suffix`",
    "text": "free text",
}


def build(df: pd.DataFrame, resolution: dict[str, dict[str, str]]) -> str:
    """Render the dictionary. *resolution* maps cohort -> {canonical: source header}."""
    lines: list[str] = []
    add = lines.append

    add("# Data dictionary")
    add("")
    add(
        "Generated by `python -m ec_wsi_2026.dataset dictionary` — **do not edit by hand**, "
        "edit `ec_wsi_2026/clinical/schema.py` or the `NOTES` map in "
        "`ec_wsi_2026/clinical/dictionary.py` instead."
    )
    add("")
    add(f"Source: {len(df)} patients across {df['cohort'].nunique()} cohorts, generated {pd.Timestamp.now():%Y-%m-%d}.")
    add("")
    add(
        "Coded columns carry numeric values whose meanings are documented — and in several "
        "cases still **unconfirmed** — in `references/code_legends.yaml`. Endpoint conventions "
        "are in `references/endpoint_definitions.md`."
    )
    add("")

    add("## Source columns")
    add("")
    add(
        "Canonical names as used in code, with the workbook header each was resolved from. "
        "The two workbooks order their columns differently, so the mapping is by name."
    )
    add("")
    rows = []
    for canonical, kind in sch.COLUMN_KIND.items():
        present = [c for c in sch.COHORTS if canonical in resolution.get(c, {})]
        if not present:
            continue
        headers = {resolution[c][canonical] for c in present}
        rows.append(
            {
                "canonical": f"`{canonical}`",
                "type": KIND_DESCRIPTIONS.get(kind, kind),
                "cohorts": "both" if len(present) == 2 else present[0][:3],
                "source header(s)": " / ".join(f"`{h}`" for h in sorted(headers)),
                "populated": _population(df, canonical),
                "notes": NOTES.get(canonical, ""),
            }
        )
    add(pd.DataFrame(rows).to_markdown(index=False))
    add("")

    add("## Derived columns")
    add("")
    source_names = set(sch.COLUMN_KIND)
    derived = [
        c
        for c in df.columns
        if c not in source_names
        and not c.endswith("__note")
        and c not in {"cohort", "source_file"}
    ]
    rows = []
    for column in sorted(derived):
        rows.append(
            {
                "column": f"`{column}`",
                "dtype": str(df[column].dtype),
                "populated": _population(df, column),
                "notes": NOTES.get(column, _endpoint_note(column)),
            }
        )
    add(pd.DataFrame(rows).to_markdown(index=False))
    add("")

    add("## Deliberately unused source columns")
    add("")
    add(
        "| Workbook column | Reason |\n|---|---|\n"
        "| `PFS (days)`, `OS (days)`, `LFFS (days)` | Entirely empty; derived from the date columns instead. |\n"
        "| `Time staging to Start CRT (days)`, `Time End CRT to OP (days)` | Entirely empty; derived. |\n"
        "| `FU TIME (days)` (definitive) | Live `DATEDIF` formulas whose cached values are stale zeros. Unreliable; follow-up is derived from dates. |"
    )
    add("")
    return "\n".join(lines) + "\n"


def _population(df: pd.DataFrame, column: str) -> str:
    """Population rate, checking the split columns a stage expands into."""
    candidates = [column, f"{column}_num", f"{column}_grade"]
    for candidate in candidates:
        if candidate in df.columns:
            n = int(df[candidate].notna().sum())
            return f"{n}/{len(df)} ({n / len(df):.0%})"
    return "—"


def _endpoint_note(column: str) -> str:
    for endpoint in ep.ENDPOINTS:
        if column == f"{endpoint.name}_event":
            return f"{endpoint.description} Cohorts: {', '.join(endpoint.cohorts)}."
        if column == f"{endpoint.name}_time":
            return f"Days from `Date Start CRT` to the {endpoint.name} event or censoring."
        if column == f"{endpoint.name}_end_date":
            return f"Date the {endpoint.name} observation ended (event or censoring)."
    return ""


def write(text: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    logger.success(f"wrote {path}")
    return path
